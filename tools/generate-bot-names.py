"""Validate the supplied 100k bot names and emit the compact compiled name pool."""

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "integration/replay/DW_BotNames.txt"
OUTPUT = ROOT / "integration/replay/DW_BotNames.h"


def generate(source):
    raw = source.read_bytes()
    names = raw.decode("utf-8-sig").splitlines()
    if len(names) != 100000:
        raise ValueError(f"Expected 100,000 names, found {len(names)}")
    # These native Com_CleanName fixed points fit name[36] without truncation,
    # color controls, unsafe punctuation, or case-insensitive duplicate display.
    seen = set()
    offsets, size = [], 0
    for line, name in enumerate(names, 1):
        if not re.fullmatch(r"[A-Za-z0-9_]{1,35}", name):
            raise ValueError(f"Line {line}: name must contain 1..35 ASCII letters/digits/underscores")
        normalized = name.lower()
        if normalized in seen:
            raise ValueError(f"Line {line}: case-insensitive duplicate name")
        seen.add(normalized)
        offsets.append(size)
        size += len(name) + 1
    digest = hashlib.sha256(raw).hexdigest()
    header = (
        "#pragma once\n#include <stdint.h>\n"
        "// Generated by tools/generate-bot-names.py from DW_BotNames.txt.\n"
        f"// Source SHA-256: {digest}\n"
        "// Native match-local names; never platform accounts. No runtime file scan.\n"
        "inline constexpr char DWBotNameData[] =\n"
        + "".join("    " + json.dumps(name + "\0").replace("\\u0000", "\\0") + "\n" for name in names)
        + ";\ninline constexpr uint32_t DWBotNameOffsets[] = {\n"
        + "".join("    " + ", ".join(map(str, offsets[i:i + 12])) + ",\n"
                  for i in range(0, len(offsets), 12))
        + "};\n"
        "inline constexpr unsigned DWBotNameCount = sizeof(DWBotNameOffsets) / sizeof(*DWBotNameOffsets);\n"
        "inline constexpr unsigned DWBotWireNameCount = 0x8000;\n"
        "static_assert(DWBotNameCount == 100000);\n"
        f"static_assert(sizeof(DWBotNameData) == {size + 1});\n"
        "// UInt16 name index plus the existing UInt16 skill, both already on\n"
        "// the native 36-byte wire record. Preserve every wire field and skill.\n"
        "inline constexpr unsigned DWBotNamePoolIndex(uint16_t index, uint16_t skill)\n"
        "{\n"
        "    return ((unsigned(index) & 0x7fff) + unsigned(skill) * DWBotWireNameCount) % DWBotNameCount;\n"
        "}\n"
        "inline const char *DWBotNameForWire(uint16_t index, uint16_t skill)\n"
        "{\n"
        "    return DWBotNameData + DWBotNameOffsets[DWBotNamePoolIndex(index, skill)];\n"
        "}\n"
    )
    return header, {"names": len(names), "maximum_name_bytes": max(map(len, names)),
                    "packed_name_bytes": size + 1, "offset_table_bytes": len(offsets) * 4,
                    "source_sha256": digest}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=INPUT)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    header, report = generate(args.input)
    if args.check:
        if args.output.read_bytes() != header.encode():
            raise ValueError("Generated bot name header does not match the authoritative list")
    else:
        args.output.write_text(header, encoding="utf-8", newline="\n")
    print(json.dumps(dict(report, header_matches=True), indent=2))


if __name__ == "__main__":
    main()
