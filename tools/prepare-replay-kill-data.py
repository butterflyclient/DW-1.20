"""Derive kill-event predicate identities from Replay's retained StringTables.

The original parser's table lookups establish the asset hashes and canonical
first-row selection. This generator does not infer event flags from names.
"""

import argparse
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = Path(r"E:\replay-compiler\evidence\workstation-stringtable-actsexport-fixed\mw19replay"
              r"\code_post_gfx\mw19replay\code_post_gfx\assets\stringtable")


def generate(proof_path, output):
    proof = json.loads(proof_path.read_bytes())
    assert proof["target_image_sha256"] == "68fb1cbcb2924182724004039de55a4c50152bb6561803c4898b7930b38132f0"
    hashes = {}
    for row in proof["cases"]:
        for name, digest in row.get("asset_sha256", {}).items():
            assert name not in hashes or hashes[name] == digest
            hashes[name] = digest
    inputs = {}

    def rows(name):
        paths = list((ASSETS / Path(name).parent).glob(Path(name).name + ".*.csv"))
        assert len(paths) == 1
        path = paths[0]
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        assert digest == hashes[name], name
        inputs[name] = dict(path=str(path), sha256=digest)
        return list(csv.reader(path.read_text(encoding="utf-8-sig").splitlines()))

    weapons, stats = rows("loot/weapon_ids.csv"), rows("mp/statstable.csv")
    canonical = {}
    for row in weapons:
        canonical.setdefault(row[1], int(row[0]))
    families = {row[4]: row[1] for row in stats if row[1] in ("weapon_dmr", "weapon_sniper")}
    members = {family: sorted(canonical[ref] for ref, selected in families.items()
                              if selected == family and ref in canonical)
               for family in ("weapon_dmr", "weapon_sniper")}
    perks, optics = {}, {}
    for row in rows("mp/perktable.csv"):
        perks.setdefault(row[1], int(row[0]))
    for row in rows("mp/reticlecategorytable.csv"):
        if row[5]:
            optics.setdefault(row[1], int(row[5]))
    assert optics["reflex"] == optics["reflexmini"] == 1
    assert optics["vzscope"] == 6
    constants = dict(Ghost=perks["specialty_ghost"], Shrapnel=perks["specialty_extra_shrapnel"],
                     Tracker=perks["specialty_tracker"], DoubleTime=perks["specialty_hustle"],
                     Reflex=optics["reflex"],
                     VariableZoom=optics["vzscope"], Ak47=canonical["iw8_ar_akilo47"])
    assert all(0 < value <= 0xFFFF for value in constants.values())
    assert all(values and len(values) == len(set(values)) and
               all(0 < value <= 0xFFFF for value in values) for values in members.values())
    lines = ["#pragma once", "#include <array>", "#include <cstdint>", "",
             "// Generated by tools/prepare-replay-kill-data.py from target Replay tables.",
             "// Native parser resolves the first matching loot row for each weapon reference."]
    lines += [f"// {name} SHA256 {item['sha256']}" for name, item in inputs.items()]
    lines += ["namespace replay_kill_data", "{"]
    for name, values in (("Marksman", members["weapon_dmr"]), ("Sniper", members["weapon_sniper"])):
        lines.append(f"    inline constexpr std::array<uint16_t, {len(values)}> {name} = {{"
                     + ", ".join(map(str, values)) + "};")
    lines += [f"    inline constexpr uint16_t {name} = {value};" for name, value in constants.items()]
    lines += ["} // namespace replay_kill_data", ""]
    target = ROOT / "src/replay_kill_data.h"
    target.write_text("\n".join(lines), encoding="utf-8")
    output.write_text(json.dumps(dict(passed=True, target_image_sha256=proof["target_image_sha256"],
        parser_proof_path=proof_path.relative_to(ROOT).as_posix(),
        parser_proof_sha256=hashlib.sha256(proof_path.read_bytes()).hexdigest(),
        tool_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(), inputs=inputs,
        families=members, constants=constants, generated=target.relative_to(ROOT).as_posix(),
        generated_sha256=hashlib.sha256(target.read_bytes()).hexdigest()), indent=2) + "\n")
    print("Generated target kill-event identities:", members, constants)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--parser-proof", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    for path in (args.parser_proof, args.output):
        assert path.resolve().is_relative_to(ROOT)
    generate(args.parser_proof.resolve(), args.output.resolve())
