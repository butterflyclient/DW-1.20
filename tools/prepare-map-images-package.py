"""Embed the published custom maps' lobby/loading images as an owned zone.

iw8-zonetool build-map-images writes data/custom-map-images (zone dw_map_images,
its techsets_ zone with the 2D materials, empty srv_/eng_/ww_ companions, a
header-only .fp beside each, and map_images.txt). The client stages these bytes
into the native zone folders at startup, like the bot-style overlay, using the
same native installation policy (bot_style_paths.derive), and loads the zone
with the frontend UI zones. Only published maps belong here: the executable
carries the zone to every player.
"""

import hashlib
import importlib.util
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "custom-map-images"
ZONE = "dw_map_images"
MAX_ZONE_BYTES = 8 * 1024 * 1024


def sha(data):
    return hashlib.sha256(data).hexdigest()


def zone_file(name):
    path = SOURCE / name
    data = path.read_bytes()
    if not data or len(data) > MAX_ZONE_BYTES:
        raise ValueError("Map image zone file has an invalid size: " + name)
    if name.endswith(".ff") and data[:4] != b"IWff":
        raise ValueError("Map image zone is not a Replay fastfile: " + name)
    if name.endswith(".fp") and data[:8] != b"IWffd100":
        raise ValueError("Map image zone patch is not a Replay patch: " + name)
    return data


def array(name, body):
    lines = [f"inline const uint8_t {name}[] = {{"]
    lines += [
        "    " + ",".join(f"0x{x:02x}" for x in body[i : i + 24]) + ","
        for i in range(0, len(body), 24)
    ]
    return "\n".join(lines + ["};"])


def render(snapshot):
    spec = importlib.util.spec_from_file_location(
        "dw_map_image_paths", ROOT / "tools/bot_style_paths.py"
    )
    paths = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(paths)
    policy = paths.derive(snapshot)
    ids = (SOURCE / "map_images.txt").read_text(encoding="ascii").split()
    if not ids or len(ids) > 64 or len(set(ids)) != len(ids) or any(
        not re.fullmatch(r"mp_[a-z0-9_]{1,12}", value) for value in ids
    ):
        raise ValueError("Invalid published map image list")
    files = {
        "primary": (zone_file(ZONE + ".ff"), zone_file(ZONE + ".fp")),
        "techsets": (zone_file("techsets_" + ZONE + ".ff"), zone_file("techsets_" + ZONE + ".fp")),
        "empty": (zone_file("srv_" + ZONE + ".ff"), zone_file("srv_" + ZONE + ".fp")),
    }
    # Every companion written by the zonetool is the same empty zone.
    for prefix in ("eng_", "ww_"):
        if (zone_file(prefix + ZONE + ".ff"), zone_file(prefix + ZONE + ".fp")) != files["empty"]:
            raise ValueError("Map image companions differ from the empty zone")
    rules = {row["name_prefix"]: row["directory"] for row in policy["installation_folder_rules"]}
    names, directories = [], []
    for prefix in sorted(rules):
        name = prefix + ZONE
        if paths.directory_for_name(name, ZONE, policy) != rules[prefix]:
            raise ValueError("Native installation directory changed for " + name)
        names.append(name)
        directories.append(rules[prefix])
    if ZONE not in names or "techsets_" + ZONE not in names:
        raise ValueError("Map image installation omits its primary or techsets zone")
    header = """#pragma once
#include <stdint.h>
// Generated by tools/prepare-map-images-package.py from data/custom-map-images.
namespace DWMapImages
{
inline constexpr const char *ZoneName = "dw_map_images";
"""
    for key, label in (("primary", ""), ("techsets", "Techsets"), ("empty", "Empty")):
        header += array(label + "Fastfile", files[key][0]) + "\n"
        header += array(label + "Patch", files[key][1]) + "\n"
    header += "inline const char *const InstallationNames[] = {\n" + "\n".join(
        '    "' + name + '",' for name in names) + "\n};\n"
    header += "inline const char *const InstallationDirectories[] = {\n" + "\n".join(
        '    "' + directory + '",' for directory in directories) + "\n};\n"
    header += "inline const char *const MapIds[] = {\n" + "\n".join(
        '    "' + value + '",' for value in ids) + "\n};\n}\n"
    proof = dict(
        schema=1,
        zone=ZONE,
        map_ids=ids,
        installation=[dict(name=n, directory=d) for n, d in zip(names, directories)],
        files={key: dict(fastfile_sha256=sha(ff), patch_sha256=sha(fp), fastfile_bytes=len(ff))
               for key, (ff, fp) in files.items()},
        installation_policy_generator=policy["policy_generator_sha256"],
    )
    return header, proof


def prepare(snapshot, proof_path=None):
    snapshot = Path(snapshot)
    header, proof = render(snapshot)
    (snapshot / "src/DW_MapImagesPackage.h").write_text(header, encoding="ascii", newline="\n")
    if proof_path:
        Path(proof_path).write_text(json.dumps(proof, indent=2) + "\n", encoding="utf-8")
    return proof


if __name__ == "__main__":
    import sys

    print(json.dumps(render(Path(sys.argv[1]))[1], indent=2))
